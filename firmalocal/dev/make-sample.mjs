import { PDFDocument, StandardFonts, rgb, degrees } from "pdf-lib";
import fs from "fs";
const doc = await PDFDocument.create();
const font = await doc.embedFont(StandardFonts.Helvetica);
const bold = await doc.embedFont(StandardFonts.HelveticaBold);
const page = doc.addPage([595, 842]);
const form = doc.getForm();
page.drawText("Solicitud de alta de cliente", { x: 50, y: 780, size: 20, font: bold });
const label = (t, y) => page.drawText(t, { x: 50, y, size: 11, font });
label("Nombre y apellidos:", 720);
const nombre = form.createTextField("nombre"); nombre.addToPage(page, { x: 180, y: 712, width: 330, height: 22 }); nombre.setFontSize(11);
label("DNI:", 680);
const dni = form.createTextField("dni"); dni.setMaxLength(9); dni.addToPage(page, { x: 180, y: 672, width: 120, height: 22 }); dni.setFontSize(11);
label("Provincia:", 640);
const prov = form.createDropdown("provincia"); prov.addOptions(["Madrid", "Barcelona", "Valencia", "Sevilla"]); prov.addToPage(page, { x: 180, y: 632, width: 160, height: 22 }); prov.setFontSize(11);
label("Tipo de cliente:", 600);
const tipo = form.createRadioGroup("tipo");
page.drawText("Particular", { x: 205, y: 600, size: 11, font }); tipo.addOptionToPage("particular", page, { x: 180, y: 596, width: 16, height: 16 });
page.drawText("Empresa", { x: 305, y: 600, size: 11, font }); tipo.addOptionToPage("empresa", page, { x: 280, y: 596, width: 16, height: 16 });
label("Acepto las condiciones", 560);
const acepto = form.createCheckBox("acepto"); acepto.addToPage(page, { x: 180, y: 556, width: 16, height: 16 });
label("Observaciones:", 520);
const obs = form.createTextField("observaciones"); obs.enableMultiline(); obs.addToPage(page, { x: 180, y: 440, width: 330, height: 90 }); obs.setFontSize(10);
page.drawText("Firma del cliente:", { x: 50, y: 380, size: 11, font });
page.drawRectangle({ x: 180, y: 320, width: 220, height: 70, borderColor: rgb(0.6,0.6,0.6), borderWidth: 1 });
page.drawText("Fecha:", { x: 50, y: 290, size: 11, font });
const p2 = doc.addPage([595, 842]);
p2.setRotation(degrees(90));
p2.drawText("Pagina 2 (girada 90 grados). Firme abajo a la derecha.", { x: 50, y: 780, size: 14, font });
fs.writeFileSync("sample-form.pdf", await doc.save());
console.log("ok");
